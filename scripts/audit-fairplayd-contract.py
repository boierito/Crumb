#!/usr/bin/env python3
"""Inspect pinned, original public-firmware inputs; does not execute fairplayd.

The inputs are research files, never distributed in Crumb. This audit establishes
launch identity, embedded entitlements and declared imports, not permission to
open an IPA, a callable XPC contract, or successful FairPlay authentication.
"""
import argparse
import hashlib
import json
import plistlib
import re
import struct
from pathlib import Path


PINS = {
    'daemon': '94d32a82fdc2a80c46b7734b20895a935836a676a34b1c3e863cdb479a68cb01',
    'launchd': 'd5c584072e2a54214c7f7ca0c2ed3c78d3bd4d5c444949c97ccb1c17a1e765f9',
    # A derived artifact, generated by ipsw v3.1.739 from the matching kernel.
    'profile': '5a2757015a13a923de2227277f44b2110c97a0f66924d11f79dd971bba225af9',
}


def pinned(path, name):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != PINS[name]:
        raise ValueError(f'{name}: unexpected input; expected pinned 24A446 artifact')
    return data


def inspect_macho(data):
    if struct.unpack_from('<I', data)[0] != 0xfeedfacf:
        raise ValueError('expected little-endian Mach-O 64')
    commands, command_bytes = struct.unpack_from('<II', data, 16)
    pos, sections, symtab, signature = 32, [], None, None
    for _ in range(commands):
        kind, size = struct.unpack_from('<II', data, pos)
        if size < 8 or pos + size > 32 + command_bytes:
            raise ValueError('invalid load command')
        if kind == 0x19:
            count = struct.unpack_from('<I', data, pos + 64)[0]
            if 72 + 80 * count > size:
                raise ValueError('invalid sections')
            for i in range(count):
                raw = struct.unpack_from('<16s16sQQIIIIIIII', data, pos + 72 + 80 * i)
                sections.append(raw)
        elif kind == 2:
            symtab = struct.unpack_from('<4I', data, pos + 8)
        elif kind == 0x1d:
            signature = struct.unpack_from('<2I', data, pos + 8)
        pos += size
    if pos != 32 + command_bytes or symtab is None or signature is None:
        raise ValueError('missing Mach-O metadata')
    so, count, strings, string_size = symtab
    imports = []
    for i in range(count):
        name, kind, _, _, _ = struct.unpack_from('<IBBHQ', data, so + 16 * i)
        if name >= string_size:
            raise ValueError('invalid symbol string')
        if kind & 0x0e == 0 and not kind & 0xe0:
            end = data.index(b'\0', strings + name, strings + string_size)
            imports.append(data[strings + name:end].decode('ascii'))
    offset, length = signature
    blob = data[offset:offset + length]
    magic, size, count = struct.unpack_from('>III', blob)
    if magic != 0xfade0cc0 or size > len(blob):
        raise ValueError('invalid signature superblob')
    entitlements = None
    for i in range(count):
        slot, start = struct.unpack_from('>II', blob, 12 + 8 * i)
        if slot == 5:
            kind, length = struct.unpack_from('>II', blob, start)
            if kind != 0xfade7171 or start + length > size:
                raise ValueError('invalid entitlement blob')
            entitlements = plistlib.loads(blob[start + 8:start + length])
    if entitlements is None:
        raise ValueError('no XML entitlement blob')
    text = next(s for s in sections if s[0].rstrip(b'\0') == b'__text')
    # Enumerate *direct* BL references to the two entitlement helper stubs.
    # Indirect calls and helper callers are not resolved by this audit.
    targets = {0x100d0f9cc: 'SecTaskCreateWithAuditToken',
               0x100d0f9bc: 'SecTaskCopyValueForEntitlement'}
    references = []
    for off in range(0, text[3], 4):
        word = struct.unpack_from('<I', data, text[4] + off)[0]
        if word & 0xfc000000 == 0x94000000:
            displacement = word & 0x3ffffff
            if displacement & (1 << 25):
                displacement -= 1 << 26
            pc = text[2] + off
            dest = pc + 4 * displacement
            if dest in targets:
                references.append({'address': hex(pc), 'import': targets[dest]})
    return entitlements, sorted(imports), references


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in PINS:
        parser.add_argument('--' + name, required=True, type=Path)
    args = parser.parse_args()
    inputs = {name: pinned(getattr(args, name), name) for name in PINS}
    launchd = plistlib.loads(inputs['launchd'])
    entitlements, imports, references = inspect_macho(inputs['daemon'])
    profile = inputs['profile'].decode('utf-8')
    explicit_read_write = re.findall(r'\((?:allow|deny)\s+file-(?:read|write)[^\s()]*', profile)
    focal_imports = ['_open', '_open_dprotected_np', '_fcntl', '_fstat', '_lstat',
                     '_read', '_container_system_path_for_identifier',
                     '_sandbox_extension_consume', '_sandbox_check',
                     '_SecTaskCreateWithAuditToken', '_SecTaskCopyValueForEntitlement']
    result = {
        'schema': 'crumb-fairplayd-static-contract-v1',
        'firmware_build': '24A446', 'device_firmware': 'iPhone17,1',
        'inputs_sha256': PINS,
        'profile_provenance': 'ipsw v3.1.739 sb dec --type protobox fairplayd.H2 --inline',
        'program': launchd['Program'], 'user': launchd['UserName'],
        'group': launchd['GroupName'], 'mach_services': launchd['MachServices'],
        'embedded_xml_entitlements': entitlements,
        'focal_imports': {name: name in imports for name in focal_imports},
        'direct_entitlement_import_calls': references,
        'profile_allow_default': '(allow default)' in profile,
        'profile_explicit_file_read_write_rules': explicit_read_write,
        'signature_cryptographically_verified_by_this_audit': False,
        'indirect_calls_resolved': False,
        'client_operation_or_required_entitlement_identified': False,
        'other_security_policy_layers_evaluated': False,
        'device_service_executed': False,
        'data_container_access_verified': False,
        'sinf_validated': False,
    }
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, StopIteration, struct.error) as error:
        raise SystemExit(str(error)) from error
