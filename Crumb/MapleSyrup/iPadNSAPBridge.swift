import Foundation
import MapleSAP
import SwiftUI
import WebKit

// Full iPadN WebAssembly/WebKit signing implementation is provided by
// CrumbSAPSigner and the verified SAPRuntime.zip, never by the old Go emulator.
extension CrumbSAPSigner {
    static let shared = CrumbSAPSigner()
}

struct CrumbSAPActionSigner: ActionSigning {
    let guid: String
    func actionSignature(body: Data) async throws -> String {
        try await CrumbSAPSigner.shared.sign(body, guid: guid, useCache: true, cacheSignature: false)
    }
}

struct CrumbSAPStoreProof: StoreProofProvider {
    func currentHeaders(guid: String) async throws -> [String: String]? {
        try await CrumbSAPSigner.shared.storeProofHeaders(guid: guid, useCache: true)
    }
    func provision(challenge: String, guid: String) async throws -> [String: String] {
        try await CrumbSAPSigner.shared.provisionStoreProof(challenge: challenge, guid: guid, useCache: true)
    }
    func reset(guid: String) async {
        await CrumbSAPSigner.shared.resetStoreProof(guid: guid)
    }
}

// Every fresh App Store KBSync is generated by iPadN's WASM signer,
// rather than Crumb's former Go SAP emulator.
struct CrumbSAPKBSyncGenerator: KBSyncGenerator {
    func generate(identity: MachineIdentity, dsid: UInt64) async throws -> Data {
        let encoded = try await CrumbSAPSigner.shared.kbsync(
            guid: identity.guid, dsid: String(dsid), useCache: true)
        guard let blob = Data(base64Encoded: encoded), !blob.isEmpty, blob.count <= 16 << 20 else {
            throw CrumbSAPToolError.message("iPadN returned invalid KBSync data")
        }
        return blob
    }
}

// Attach the signer WKWebView to the iOS view hierarchy. Detached WebViews can
// suspend background script evaluation, leaving authentication hanging.
struct CrumbSAPWebView: UIViewRepresentable {
    let webView: WKWebView
    func makeUIView(context: Context) -> WKWebView { webView }
    func updateUIView(_ view: WKWebView, context: Context) { }
}
